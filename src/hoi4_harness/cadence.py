"""How often the mod writes its telemetry (state, front and, with them, the army, war and
probe lines), and the console lines that set it.

The mod's default is once per in-game day, from ``on_daily``. Two other shapes are offered:

* **faster**: HOI4 has no hourly on_action, so the mod schedules a hidden event with a delay in
  hours that reschedules itself (``common/scripted_effects/llm_bridge_cadence.txt`` and
  ``events/llm_bridge_cadence_events.txt``, generated by ``modgen``). The delay in
  ``country_event = { id = .. hours = .. }`` is a literal in every vanilla use and the
  documentation shows no variable form, so there is one event per supported value instead of
  one event with a variable delay;
* **slower**: every N days, counted in the daily tick.

One number says which: ``telemetry_hours``. 24 is the default (today's behaviour, no chain);
below 24 is the event chain; a multiple of 24 is every N days. Only the values listed here are
generated, so a typo is refused at the start of a run instead of sending an effect the game
does not know. The weekly ``camp`` line and the event lines are not affected.
"""

from __future__ import annotations

#: Hours between two telemetry ticks that divide the day: the event chain.
SUBDAILY_HOURS = (1, 2, 3, 4, 6, 8, 12)
DAILY_HOURS = 24
#: Whole days between two ticks, for the slower side.
SLOW_DAYS = (2, 3, 4, 5, 6, 7, 10, 14, 30)
SUPPORTED_HOURS = (*SUBDAILY_HOURS, DAILY_HOURS, *(days * 24 for days in SLOW_DAYS))


def validate(hours: object) -> int:
    """``hours`` as an int, or ``ValueError`` naming what is supported."""
    if isinstance(hours, bool) or not isinstance(hours, (int, float, str)):
        raise ValueError(f"telemetry_hours must be a number of hours, not {hours!r}")
    try:
        number = float(hours)
    except ValueError:
        raise ValueError(f"telemetry_hours must be a number of hours, not {hours!r}") from None
    if number != int(number) or int(number) not in SUPPORTED_HOURS:
        raise ValueError(f"telemetry_hours = {hours} is not supported; use one of "
                         f"{', '.join(str(h) for h in SUPPORTED_HOURS)} (24 is the default: once "
                         "a day; above 24, every N days)")
    return int(number)


def effect_name(hours: int) -> str:
    """The scripted effect that sets the cadence (generated for every supported value)."""
    return f"llm_bridge_telemetry_every_{validate(hours)}h"


def lines(tag: str, hours: int) -> list[str]:
    """The console line that sets the cadence for ``tag``'s scope (the player's, or a rival's)."""
    return [f"effect {tag.upper()} {effect_name(hours)}"]


def console(adapter) -> object | None:
    """The console channel of a headless adapter, or None (the mock has none)."""
    writer = getattr(adapter, "writer", None)
    return getattr(getattr(writer, "router", None), "console", None)


def apply(console_channel, tag: str, hours: int | None, say=None) -> bool:
    """Send the cadence for ``tag`` through the console and say what was set. ``hours`` None is
    the default (leave the game as it is: nothing is sent). Returns whether a line went out.

    The mod answers with an ``evt`` line (kind 20) that the reader turns into a
    ``telemetry cadence`` event, so the game.log shows it took; this only says what was asked."""
    if hours is None or console_channel is None or not tag:
        return False
    wanted = lines(tag, hours)
    if say is not None:
        say(f"telemetry cadence: {describe(hours)} ({wanted[0]})")
    console_channel.send_lines(wanted)
    return True


def describe(hours: int) -> str:
    hours = validate(hours)
    if hours < DAILY_HOURS:
        return f"every {hours} in-game hour{'s' if hours > 1 else ''} (the event chain)"
    if hours == DAILY_HOURS:
        return "once per in-game day (the default)"
    return f"every {hours // 24} in-game days"
