"""Front orders: the LLM picks a state and says what its front should do there (push, attack,
probe, hold), and the game's own armies carry it out.

Script cannot move a single division (there is no division scope), and the mouse would fight the
person for input. The game's AI layer is finer than the directives, though: ``front_control``
sets a front's execution (careful, balanced, rush), forces the attack on or off and allows probing
attacks; ``front_unit_request`` puts more divisions on it. Both take a ``state_trigger``, so fixed
blocks in the mod (``llm_bridge_front_orders.txt``) apply to whatever states carry an order flag,
and the inbox sets the flags:

    POL = { 123 = { clr_state_flag = ...  set_state_flag = llmb_front_push } }

A ``front_control`` applies to the front(s) the flagged state lies on, so an order on a state
steers that stretch of the line. Only one LLM country should give front orders in a game: the
flags sit on the states, so two LLM countries on the same front would read each other's.
"""

from __future__ import annotations

import json
from pathlib import Path

#: order -> (front_control fields, extra divisions requested). ``hold`` turns the attack off.
ORDERS: dict[str, tuple[str, int]] = {
    "push": ("execution_type = rush execute_order = yes manual_attack = yes", 150),
    "attack": ("execution_type = balanced execute_order = yes manual_attack = yes", 80),
    "probe": ("execution_type = careful execute_order = yes manual_attack = yes", 30),
    "hold": ("execution_type = careful execute_order = no manual_attack = no", 60),
}
FLAG = "llmb_front_{order}"
PRIORITY = 300
FILE = "common/ai_strategy/llm_bridge_front_orders.txt"
STANDING = "front_orders.json"


def strategies() -> str:
    out = [
        "# GENERATED by src/hoi4_harness/front_orders.py (via modgen). Do not edit by hand.",
        "#",
        "# Front orders (set_front_order): a state flag per order, set by the harness through the",
        "# inbox; each block steers the front(s) a flagged state lies on. ai_strategy/_documentation.md",
        "# (1.20): front_control and front_unit_request take state_trigger. ratio = 0: any share of",
        "# the front being flagged is enough. Priority 300 sits above the game's own front plans.",
        "",
    ]
    for order, (control, request) in ORDERS.items():
        flag = FLAG.format(order=order)
        out += [
            f"llmb_front_{order} = {{",
            f"\tenable = {{ llm_bridge_is_harness = yes any_state = {{ has_state_flag = {flag} }} }}",
            f"\tabort = {{ OR = {{ llm_bridge_is_harness = no "
            f"NOT = {{ any_state = {{ has_state_flag = {flag} }} }} }} }}",
            f"\tai_strategy = {{ type = front_control state_trigger = {{ has_state_flag = {flag} }} "
            f"ratio = 0 priority = {PRIORITY} ordertype = front {control} }}",
            f"\tai_strategy = {{ type = front_unit_request state_trigger = {{ has_state_flag = {flag} }} "
            f"value = {request} }}",
            "}",
            "",
        ]
    return "\n".join(out)


def effect(state: int, order: str) -> str:
    """The script, in the ordering country's scope, that leaves ``state`` with ``order`` only."""
    clears = " ".join(f"clr_state_flag = {FLAG.format(order=o)}" for o in ORDERS)
    body = clears
    if order != "clear":
        body += f" set_state_flag = {FLAG.format(order=order)}"
    return f"{state} = {{ {body} }}"


class Standing:
    """The orders this run has given and the game confirmed, kept in the run folder."""

    def __init__(self, run_dir: Path | None):
        self.path = Path(run_dir) / STANDING if run_dir else None
        self.orders: dict[str, str] = {}
        if self.path and self.path.exists():
            try:
                self.orders = json.loads(self.path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                self.orders = {}

    def record(self, state: int, order: str) -> None:
        if order == "clear":
            self.orders.pop(str(state), None)
        else:
            self.orders[str(state)] = order
        if self.path:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.path.write_text(json.dumps(self.orders, sort_keys=True), encoding="utf-8")

    def line(self, names=None) -> str | None:
        if not self.orders:
            return None
        parts = []
        for sid, order in sorted(self.orders.items(), key=lambda kv: (kv[1], int(kv[0]))):
            name = names(int(sid)) if names else f"state {sid}"
            parts.append(f"{order} {name}")
        return "  Front orders standing: " + "; ".join(parts)
