"""Region orders: the LLM tells its navy and air force where to fight, by strategic region, and the
game's own AI carries it out (headless micro beyond the land front).

The game's naval and air AI is steered per strategic region (``common/ai_strategy/_documentation.md``
and the game's own ENG.txt use them: ``naval_dominance``, ``naval_convoy_raid_region``,
``naval_avoid_region``, ``strike_force_home_base``, ``strategic_air_importance``). Those take a
region id, not a trigger, so one block per (region, order) is generated from the playset's
``map/strategicregions`` and keyed on a COUNTRY flag the inbox sets on the ordering country, so two
LLM countries never read each other's orders.

    POL = { clr_country_flag = llmb_region_<order>_<id> ... set_country_flag = llmb_region_raid_16 }
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

#: order -> (strategy type, value, needs a sea region). Values follow the game's own files: ENG.txt
#: uses naval_avoid_region 500, strike_force_home_base 70-250, naval_convoy_raid_region 100;
#: naval_dominance is a percentage; strategic_air_importance ~35,000 is a main front in combat.
ORDERS: dict[str, tuple[str, int, bool]] = {
    "dominate": ("naval_dominance", 90, True),
    "raid_convoys": ("naval_convoy_raid_region", 300, True),
    "avoid": ("naval_avoid_region", 500, True),
    "home_base": ("strike_force_home_base", 250, True),
    "air_superiority": ("strategic_air_importance", 40000, False),
}
FLAG = "llmb_region_{order}_{region}"
FILE = "common/ai_strategy/llm_bridge_regions.txt"


@dataclass
class Region:
    id: int
    name_key: str
    provinces: list[int] = field(default_factory=list)
    sea: bool = False
    name: str = ""


_ID = re.compile(r"\bid\s*=\s*(\d+)")
_NAME = re.compile(r'\bname\s*=\s*"?([\w.\-]+)"?')
_PROVINCES = re.compile(r"provinces\s*=\s*\{([^}]*)\}", re.S)


def read_regions(playset) -> dict[int, Region]:
    """The playset's strategic regions, with whether they are sea regions (from definition.csv)."""
    from .mapdata import read_definitions, resolve_file

    kinds: dict[int, str] = {}
    definitions = resolve_file(playset, "map/definition.csv")
    if definitions is not None:
        kinds = {p.id: p.kind for p in read_definitions(
            definitions.read_text(encoding="utf-8-sig", errors="replace")).values()}
    out: dict[int, Region] = {}
    for path in playset.layered("map/strategicregions", "*.txt"):
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig", errors="replace"))
        ident, name, provs = _ID.search(text), _NAME.search(text), _PROVINCES.search(text)
        if not ident:
            continue
        provinces = [int(p) for p in provs.group(1).split()] if provs else []
        # A sea region can hold an island or a strip of coast: most of it being sea is what counts.
        wet = sum(1 for p in provinces if kinds.get(p) == "sea")
        sea = bool(provinces) and wet * 2 > len(provinces)
        out[int(ident.group(1))] = Region(int(ident.group(1)), name.group(1) if name else "",
                                          provinces, sea)
    return out


def name_regions(regions: dict[int, Region], names) -> None:
    found = names({r.name_key for r in regions.values() if r.name_key})
    for r in regions.values():
        r.name = found.get(r.name_key, "") or r.name_key


def strategies(regions: dict[int, Region]) -> str:
    out = [
        "# GENERATED by src/hoi4_harness/regions.py from the playset's strategic regions",
        "# (hoi4-harness mod-probe). Do not edit by hand. set_region_order: the ordering country",
        "# carries llmb_region_<order>_<region>; each block steers its own navy or air force there.",
        "",
    ]
    for rid in sorted(regions):
        region = regions[rid]
        for order, (kind, value, sea) in ORDERS.items():
            if sea and not region.sea:
                continue
            flag = FLAG.format(order=order, region=rid)
            out += [
                f"{flag} = {{",
                f"\tenable = {{ has_country_flag = {flag} }}",
                f"\tabort = {{ NOT = {{ has_country_flag = {flag} }} }}",
                f"\tai_strategy = {{ type = {kind} id = {rid} value = {value} }}",
                "}",
                "",
            ]
    return "\n".join(out)


def effect(region: int, order: str) -> str:
    """The script, in the ordering country's scope, that leaves ``region`` with ``order`` only."""
    clears = " ".join(f"clr_country_flag = {FLAG.format(order=o, region=region)}" for o in ORDERS)
    if order == "clear":
        return clears
    return f"{clears} set_country_flag = {FLAG.format(order=order, region=region)}"


def resolve(regions: dict[int, Region], value: str) -> Region | None:
    text = str(value).strip()
    if text.isdigit():
        return regions.get(int(text))
    low = text.lower()
    for r in regions.values():
        if low in (r.name.lower(), r.name_key.lower()):
            return r
    # A partial name the LLM would type ("Western Mediterranean" for "Western Mediterranean Sea"):
    # accepted only when exactly one region contains it.
    hits = [r for r in regions.values() if low and low in r.name.lower()]
    return hits[0] if len(hits) == 1 else None


def write(mod_dir: Path, regions: dict[int, Region]) -> Path:
    target = Path(mod_dir) / FILE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(strategies(regions), encoding="utf-8", newline="\n")
    return target
