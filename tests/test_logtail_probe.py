"""The focus/research probe: which focus and technologies are running (#2).

Lines are as 1.19.5.0 prints them: an engine prefix, then LLMB|v3|focus|... or
|research|... right behind that day's state line.
"""

from pathlib import Path

from hoi4_harness import modgen
from hoi4_harness.adapters.logtail import LogTailAdapter
from hoi4_harness.identifiers import IdentifierIndex, Playset

PLAYSET = Path(__file__).parent / "fixtures" / "playset" / "game"
MOD = Path(__file__).resolve().parents[1] / "mod" / "llm_bridge"


def stamp(d, hour=21):
    return f"[11:04:29][1936.01.{d:02d}.{hour}]: "


def state(d, tag="SWE", techs=None):
    extra = f"|techs={techs}" if techs is not None else ""
    return (f"{stamp(d)}LLMB|v3|state|date= 21:00, {d} January, 1936|tag={tag}|pp=1|stab=80|ws=0"
            f"|civ=9|mil=3|doc=3|mp=5{extra}\n")


def focus(d, ident, tag="SWE"):
    return f"{stamp(d)}LLMB|v3|focus|tag={tag}|id={ident}\n"


def research(d, ident, tag="SWE"):
    return f"{stamp(d)}LLMB|v3|research|tag={tag}|id={ident}\n"


def read(tmp_path, *lines):
    path = tmp_path / "game.log"
    path.write_text("".join(lines), encoding="utf-8")
    return LogTailAdapter(path).read_state()


def events(state_):
    return [(e.kind, e.text) for e in state_.events]


def test_the_running_focus_and_research_fill_the_state(tmp_path):
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), research(2, "gwtank"), research(2, "basic_train"))
    assert s.national_focus == "SWE_rearm"
    assert [r.technology for r in s.research] == ["gwtank", "basic_train"]
    assert "national_focus" not in s.unknown_fields and "research" not in s.unknown_fields


def test_a_day_with_no_focus_line_means_no_focus_is_running(tmp_path):
    # Day 3 has no focus line, and the next state line closes it.
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3), state(4))
    assert s.national_focus is None and s.research == []


def test_a_poll_between_a_state_line_and_its_probes_still_shows_the_running_focus(tmp_path):
    # Seen live: the reader cleared the focus on the state line, so a poll that
    # landed before the probe lines read "no focus" and woke the planner.
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3))
    assert s.national_focus == "SWE_rearm"


def test_a_focus_that_stops_answering_is_focus_complete(tmp_path):
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3), focus(3, "SWE_rearm"),
             state(4), state(5))
    assert events(s) == [("focus_complete", "focus complete: SWE_rearm")]


def test_a_focus_still_running_is_not_complete(tmp_path):
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3), focus(3, "SWE_rearm"),
             state(4), focus(4, "SWE_rearm"))
    assert events(s) == []


def test_switching_straight_to_the_next_focus_completes_the_first(tmp_path):
    s = read(tmp_path, state(2), focus(2, "A"), state(3), focus(3, "B"), state(4), focus(4, "B"))
    assert events(s) == [("focus_complete", "focus complete: A")]


def test_a_finished_technology_without_the_counter_is_research_done(tmp_path):
    s = read(tmp_path, state(2), research(2, "gwtank"), state(3), state(4))
    assert events(s) == [("research_done", "research complete: gwtank")]


def test_with_the_counter_one_event_names_the_technology(tmp_path):
    s = read(tmp_path, state(2, techs=10), research(2, "gwtank"),
             state(3, techs=11), state(4, techs=11))
    assert events(s) == [("research_done", "research complete: 1 new technology (11 researched): gwtank")]


def test_a_partly_written_tick_never_reports_a_completion(tmp_path):
    # The state line is on disk but the probe lines behind it are not yet.
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3))
    assert events(s) == []


def test_probe_lines_of_another_day_or_country_are_not_this_ticks(tmp_path):
    s = read(tmp_path, state(2), focus(2, "SWE_rearm"), state(3),
             focus(2, "STALE"), focus(3, "POL_x", tag="POL"), state(4))
    assert s.national_focus is None


def test_the_generated_probe_covers_the_fixture_playset():
    index = IdentifierIndex.build(Playset.from_paths(PLAYSET))
    text = modgen.generate_probe(index).text
    assert text == modgen.generate_probe(index).text            # deterministic
    assert "llm_bridge_emit_probe = {" in text and text.count("{") == text.count("}")
    assert "has_focus_tree = " in text
    assert "is_researching_technology = " in text
    for focus_id in index.trees[0].focuses:
        assert f"focus = {focus_id} progress > 0" in text
    for tech in index.technologies:
        assert f"is_researching_technology = {tech} " in text


def test_the_committed_probe_is_generated_and_called_by_the_telemetry():
    probe = (MOD / modgen.PROBE_PATH).read_text(encoding="utf-8")
    assert probe.startswith("# GENERATED by `hoi4-harness mod-probe`")
    assert probe.count("{") == probe.count("}")
    assert "LLMB|v3|focus|tag=[THIS.GetTag]|id=" in probe
    telemetry = (MOD / "common/scripted_effects/llm_bridge_telemetry.txt").read_text(encoding="utf-8")
    assert "llm_bridge_emit_probe = yes" in telemetry


def test_the_reader_counts_complete_days_of_telemetry(tmp_path):
    assert read(tmp_path, state(2), focus(2, "SWE_rearm")).telemetry_ticks is None
    assert read(tmp_path, state(2), state(3), state(4)).telemetry_ticks == 2
